    public double realEsf(){
        double valorReal;
        valorReal = valorConductores * nominalEsf();
        
        return redondear(valorReal, 2);
    }
    
    public double nominalEsf(){
        double valorNominal=0;
        if(tipoModelo.equals("organico")){
            valorNominal=3.2 *pow(tamanoLineas,1.05);
        }else if(tipoModelo.equals("moderado")){
            valorNominal=3 *pow(tamanoLineas,1.12);
        }else if(tipoModelo.equals("embebido")){
            valorNominal=2.8*pow(tamanoLineas,1.2);
        }
        
        return redondear(valorNominal, 2);
    }
    
    
    
    public static double redondear (double Num, int Decimales){
        int aux=1;
        for (int i=0;i<Decimales;i++){
            aux=aux*10;
        }
        Num=Num*aux;
        Num=(double)Math.round(Num);
        Num=Num/aux; 
        return(Num);
    }
    
    public double tiempoDes(){
        double tiempoDes;
        if(tipoModelo.equals("organico")){
            tiempoDes=2.5 *pow(realEsf(),0.38);
        }else if(tipoModelo.equals("moderado")){
            tiempoDes=2.5 *pow(realEsf(),0.35);
        }else{
            tiempoDes=2.5*pow(realEsf(),0.32);
        }
        
        return redondear(tiempoDes,2);
    }
    
    public double costoReque(){
        double valorCostoReque;
        valorCostoReque = realEsf() *costoPersonaMesReque;
        return redondear(valorCostoReque,2);
    }
    
    public double costoPrograma(){
        double valorCostoPrograma;
        valorCostoPrograma=realEsf() *costoPersonaMesProgra;
        return redondear(valorCostoPrograma,2);
    }
    
    public double costoDis(){
        double valorCostoAnalisis;
        valorCostoAnalisis=realEsf() *costoPersonaMesDise;
        return redondear(valorCostoAnalisis,2);
    }
    
    public double costoAnalisis(){
        double valorCostoPruebas;
        valorCostoPruebas=realEsf() * costoPersonaMesAnalisis;
        return redondear(valorCostoPruebas,2);
    }
    
    public double costoTotal(){
        double total = costoAnalisis()+ costoDis() + costoPrograma()+costoReque();
        return total;
    }
    
