    public resCasosUso(double actores,double caso,double totalT,double totalF, int hora){
        initComponents();
        setLocationRelativeTo(null);
        double pcusa = actores+caso;
        double fct= 0.6+0.01*totalT;
        double fa= 1.4+(-0.03*totalF);
        double pcua = pcusa*fct*fa;
        PA.setText(""+actores);
        PCU.setText(""+caso);
        PCUSA.setText(""+pcusa);
        FCT.setText(""+redondear(fct,3));
        FA.setText(""+redondear(fa,3));
        PCUA.setText(""+redondear(pcua, 3));
        if(hora == 20 || hora == 28 ){
            double esf = hora * pcua;
            ESF.setText(redondear(esf, 3) + " hs.hombre");
        }else {
             ESF.setText("Reduce este valor");
        }
    }
    
    public static double redondear (double Num, int Decimales){
        int aux=1;
        for (int i=0;i<Decimales;i++){
            aux=aux*10;
        }
        Num=Num*aux;
        Num=(double)Math.round(Num);
        Num=Num/aux; 
        return(Num);
    }

