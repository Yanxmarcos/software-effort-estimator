    private void buttonEstimarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_buttonEstimarMouseClicked
        if (!checkLDC.isSelected() && !checkKLDC.isSelected()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecciona LDC o KLDC.",
                    "Entrada inválida", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            costoPersonaMesReque = EntradaNumerica.noNegativa(inputRequerimientos.getText(), "Costo de requerimientos");
            costoPersonaMesDise = EntradaNumerica.noNegativa(inputDiseno.getText(), "Costo de diseño");
            costoPersonaMesProgra = EntradaNumerica.noNegativa(inputProgramacion.getText(), "Costo de programación");
            costoPersonaMesAnalisis = EntradaNumerica.noNegativa(inputAnalisis.getText(), "Costo de análisis");
            tamanoLineas = EntradaNumerica.noNegativa(tamLineasCode.getText(), "Tamaño del proyecto");
        } catch (IllegalArgumentException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Entrada inválida", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        nombProyecto = nombreProyecto.getText();
        double tamanoKldc = checkLDC.isSelected() ? tamanoLineas / 1000 : tamanoLineas;
        double valorConductores= conductoresCosto();
        cocomoInterRes estimacionHallada = new cocomoInterRes( nombProyecto, tipoModelo, costoPersonaMesReque, costoPersonaMesDise,
             costoPersonaMesProgra, costoPersonaMesAnalisis,valorConductores,tamanoKldc,tipoTamano);
        estimacionHallada.setVisible(true);
    }//GEN-LAST:event_buttonEstimarMouseClicked

