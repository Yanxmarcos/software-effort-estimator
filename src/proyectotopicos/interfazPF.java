    private void jButton2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton2MouseClicked
        try {
            double entradas = pesoEntradaBaja * EntradaNumerica.cantidad(entradaBaja.getText(), "Entradas (baja)")
                    + pesoEntradaMedia * EntradaNumerica.cantidad(entradaMedia.getText(), "Entradas (media)")
                    + pesoEntradaAlta * EntradaNumerica.cantidad(entradaAlta.getText(), "Entradas (alta)");
            double salidas = pesoSalidaBaja * EntradaNumerica.cantidad(salidaBaja.getText(), "Salidas (baja)")
                    + pesoSalidaMedia * EntradaNumerica.cantidad(salidaMedia.getText(), "Salidas (media)")
                    + pesoSalidaAlta * EntradaNumerica.cantidad(salidaAlta.getText(), "Salidas (alta)");
            double consultas = pesoConsultaBaja * EntradaNumerica.cantidad(consultaBaja.getText(), "Consultas (baja)")
                    + pesoConsultaMedia * EntradaNumerica.cantidad(consultaMedia.getText(), "Consultas (media)")
                    + pesoConsultaAlta * EntradaNumerica.cantidad(consultaAlta.getText(), "Consultas (alta)");
            double archivos = pesoArchivosBaja * EntradaNumerica.cantidad(archivosBaja.getText(), "Archivos (baja)")
                    + pesoArchivosMedia * EntradaNumerica.cantidad(archivosMedia.getText(), "Archivos (media)")
                    + pesoArchivosAlta * EntradaNumerica.cantidad(archivosAlta.getText(), "Archivos (alta)");
            double interfaces = pesoInterfacesBaja * EntradaNumerica.cantidad(interfacesBaja.getText(), "Interfaces (baja)")
                    + pesoInterfacesMedia * EntradaNumerica.cantidad(interfacesMedia.getText(), "Interfaces (media)")
                    + pesoInterfacesAlta * EntradaNumerica.cantidad(interfacesAlta.getText(), "Interfaces (alta)");

            suma = entradas + salidas + consultas + archivos + interfaces;
            equivalenteLineas = equivalenteEntorno[comboEquivalencia.getSelectedIndex()] * suma;
            salidaSumatoria.setText(Long.toString((long) suma));
            equivalenteLDC.setText(Long.toString((long) equivalenteLineas));
        } catch (IllegalArgumentException ex) {
            salidaSumatoria.setText("");
            equivalenteLDC.setText("");
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Entrada inválida", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton2MouseClicked

